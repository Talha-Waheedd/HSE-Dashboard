-- Summary of seeded hazards
SELECT
    h.hazard_number,
    h.title,
    hc.category_name,
    ht.type_name,
    rr.rating_name,
    s.status_name,
    h.date_reported,
    h.target_completion_date,
    h.is_overdue
FROM hazards h
JOIN hazard_categories  hc  ON h.category_id        = hc.category_id
LEFT JOIN hazard_types  ht  ON h.hazard_type_id      = ht.hazard_type_id
LEFT JOIN risk_ratings  rr  ON h.risk_rating_id      = rr.risk_rating_id
JOIN statuses           s   ON h.status_id           = s.status_id
ORDER BY h.hazard_id;

-- Dashboard KPI query — hazards by status
SELECT
    s.status_name,
    s.color,
    COUNT(h.hazard_id) AS total
FROM statuses s
LEFT JOIN hazards h ON h.status_id = s.status_id AND h.deleted_at IS NULL
WHERE s.module_name = 'hazards'
GROUP BY s.status_id, s.status_name, s.color
ORDER BY s.display_order;
